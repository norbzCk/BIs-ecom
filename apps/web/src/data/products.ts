export const productById = (id: string) => products.find((p) => p.id === id)
export const productBySlug = (slug: string) => products.find((p) => p.slug === slug)

export const productsInCategory = (category: string) =>
  products.filter((p) => p.category === category)

/** Same category first, then anything else, never the product itself. */
export function relatedProducts(product: Product, limit = 4): Product[] {
  const sameCategory = products.filter(
    (p) => p.id !== product.id && p.category === product.category,
  )
  const rest = products.filter((p) => p.id !== product.id && p.category !== product.category)
  return [...sameCategory, ...rest].slice(0, limit)
}

export const featuredProducts = () => products.filter((p) => p.featured)

export const dealProducts = () =>
  products
    .filter((p) => p.compareAtPrice && p.compareAtPrice > p.price)
    .map((p) => ({ product: p, off: Math.round((1 - p.price / p.compareAtPrice!) * 100) }))
    .sort((a, b) => b.off - a.off)

export function relatedReviews(productId: string): Review[] {
  const product = productById(productId)
  if (!product) return []
  const scoped = reviews.filter((r) => r.product === product.name)
  return scoped.length > 0 ? scoped : reviews
}

